(function (global) {
  const GENERATOR_ORIGIN = 'https://solanareplygenerator.lol';
  const MENU_ID = 'create-solana-reply';
  const ATTRIBUTION = 'reply generated by https://solanareplygenerator.lol';

  function extractTweetId(value) {
    const text = String(value || '').trim();
    if (/^\d{5,}$/.test(text)) return text;

    const match = text.match(/(?:x\.com|twitter\.com)\/(?:i\/)?[^/\s]+\/status\/(\d+)|(?:x\.com|twitter\.com)\/i\/status\/(\d+)/i);
    return match ? match[1] || match[2] : '';
  }

  function normalizeTweetUrl(tweetId) {
    return tweetId ? `https://x.com/i/status/${tweetId}` : '';
  }

  function getTweetTarget(info, tab) {
    const candidates = [
      info && info.linkUrl,
      info && info.pageUrl,
      tab && tab.url,
      info && info.selectionText,
    ].filter(Boolean);

    for (const sourceUrl of candidates) {
      const tweetId = extractTweetId(sourceUrl);
      if (tweetId) {
        return {
          sourceUrl,
          tweetId,
          tweetUrl: normalizeTweetUrl(tweetId),
        };
      }
    }

    return {
      sourceUrl: candidates[0] || '',
      tweetId: '',
      tweetUrl: '',
    };
  }

  function buildGeneratorUrl(target) {
    const url = new URL(GENERATOR_ORIGIN);
    if (target && (target.tweetUrl || target.sourceUrl)) {
      url.searchParams.set('tweetUrl', target.tweetUrl || target.sourceUrl);
    }
    return url.toString();
  }

  function buildReplyIntentUrl(tweetId, replyText) {
    const url = new URL('https://x.com/intent/post');
    url.searchParams.set('in_reply_to', tweetId);
    url.searchParams.set('text', `${replyText}\n\n${ATTRIBUTION}`);
    return url.toString();
  }

  async function requestReply(target, fetchImpl) {
    const response = await fetchImpl(`${GENERATOR_ORIGIN}/api/reply`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        tweetUrl: target.tweetUrl,
        tweetId: target.tweetId,
      }),
    });

    const data = await response.json().catch(() => ({}));
    if (!response.ok || !data.text) {
      throw new Error(data.error || `reply_api_${response.status || 'failed'}`);
    }
    return String(data.text).trim();
  }

  async function handleContextMenuClick(info, tab, dependencies) {
    if (!info || info.menuItemId !== MENU_ID) {
      return { action: 'ignored' };
    }

    const deps = dependencies || {};
    const fetchImpl = deps.fetch || global.fetch;
    const openTab = deps.openTab;
    const target = getTweetTarget(info, tab);

    if (!target.tweetId || !fetchImpl) {
      await openTab(buildGeneratorUrl(target));
      return { action: 'open-generator', target };
    }

    try {
      const replyText = await requestReply(target, fetchImpl);
      await openTab(buildReplyIntentUrl(target.tweetId, replyText));
      return { action: 'open-reply-intent', target };
    } catch (error) {
      await openTab(buildGeneratorUrl(target));
      return { action: 'open-generator', target, error: error.message };
    }
  }

  global.SolReplyExtension = {
    ATTRIBUTION,
    GENERATOR_ORIGIN,
    MENU_ID,
    buildGeneratorUrl,
    buildReplyIntentUrl,
    extractTweetId,
    getTweetTarget,
    handleContextMenuClick,
    normalizeTweetUrl,
    requestReply,
  };
})(globalThis);
